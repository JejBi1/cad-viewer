/// An error whose text is shown as is (never produced from an OCCT exception).
class Fail : public std::runtime_error {
 public:
  explicit Fail(const std::string& msg) : std::runtime_error(msg) {}
};

/// Re-throws the exception being handled as a std::runtime_error with a readable message. Never returns.
[[noreturn]] void rethrow_as_runtime();

/// Runs `fn(arg)` and returns 0, or the code of a hardware exception (access violation and similar) that
/// escaped from it. C++ exceptions pass through. Windows only; elsewhere it just calls `fn`.
unsigned long run_guarded(void (*fn)(void*), void* arg);

/// Test support (`raw::test_inject_fault`): after `test_inject_fault(id)` the next `fault_point(id)` of the same thread
/// raises a hardware fault (an access violation, as OCCT does on a damaged input) once; 0 switches it off. A few bridge functions call
/// `fault_point` inside their guarded region, so that the tests can check that such a fault becomes an error, leaves no
/// lock behind and does not end the process. Windows only; inert elsewhere and whenever nothing was injected.
void test_inject_fault(uint32_t id);
void fault_point(uint32_t id);
inline constexpr uint32_t FAULT_FACE_NORMAL = 1;
inline constexpr uint32_t FAULT_READ_STL = 2;

/// Calls `f` so that a crash inside OCCT (for instance on a corrupt file) becomes a C++ exception (`Fail`)
/// instead of ending the process.
template <class R, class F>
R guarded(F&& f) {
  using FT = std::remove_reference_t<F>;
  unsigned long code = 0;
  if constexpr (std::is_void_v<R>) {
    auto thunk = [](void* p) { (*static_cast<FT*>(p))(); };
    code = run_guarded(+thunk, &f);
    if (code != 0) throw Fail("Chyba geometrického jádra: neplatný přístup do paměti (poškozený vstup?).");
  } else {
    std::optional<R> out;
    auto call = [&]() { out.emplace(f()); };
    auto thunk = [](void* p) { (*static_cast<decltype(call)*>(p))(); };
    code = run_guarded(+thunk, &call);
    if (code != 0) throw Fail("Chyba geometrického jádra: neplatný přístup do paměti (poškozený vstup?).");
    return std::move(*out);
  }
}

// BR_BEGIN(R) ... BR_END wraps the body of a bridge function returning R: hardware exceptions and every C++
// exception become a std::runtime_error (cxx turns it into a Rust Err); nothing escapes as an abort.
#define BR_BEGIN(RET) \
  try {               \
    return ::stepview::guarded<RET>([&]() -> RET {
#define BR_END                        \
  });                                 \
  }                                   \
  catch (...) {                       \
    ::stepview::rethrow_as_runtime(); \
  }

/// A distinct part shape (non-assembly label of the XCAF shape table).
struct Proto {
  TDF_Label label;
  std::string key;  // OCCT label entry, e.g. "0:1:1:2"
  TopoDS_Shape shape;
  bool shape_loaded = false;
  bool mesh_only = false;
  bool maps_ready = false;
  ShapeMap faces, edges, verts;  // unique sub-shapes in TopExp::MapShapes order (the EntityRef index space)
};

/// One node of the instance tree (assembly or part instance).
struct TNode {
  TDF_Label label;        // instance (reference) label, or the prototype itself for a free shape
  TDF_Label proto_label;  // the prototype (referred shape) label
  int parent = -1;
  int proto = -1;         // index into Doc::protos for parts, -1 for assemblies
  bool is_asm = false;
  TopLoc_Location loc;    // world location (parent * reference location)
  std::vector<int> children;
};

class Doc {
 public:
  occ::handle<TDocStd_Document> doc;

  mutable std::vector<std::unique_ptr<Proto>> protos;
  mutable std::unordered_map<std::string, uint32_t> proto_by_key;
  mutable bool protos_ready = false;

  mutable std::vector<TNode> nodes;
  mutable bool tree_built = false;

  mutable std::vector<TopoDS_Shape> mesh_shapes;  // filled by doc_mesh_items, consumed by doc_mesh_run

  void ensure_protos() const;
  Proto& proto(uint32_t id) const;
  const TopoDS_Shape& proto_shape(Proto& p) const;
  void ensure_maps(Proto& p) const;
  uint32_t proto_for_label(const TDF_Label& lab) const;
  void build_tree() const;
  TopoDS_Shape located_shape(const TNode& n) const;
  /// Leaf node indices below `node` (itself when it is a part), in tree order.
  void leaves_of(uint32_t node, std::vector<uint32_t>& out) const;
};

class CadReader {
 public:
  std::unique_ptr<STEPCAFControl_Reader> step;
  std::unique_ptr<IGESCAFControl_Reader> iges;
};

/// State of one interference run (collisions.py: run). Rust drives the loop pair by pair.
class InterfRun {
 public:
  struct Item {
    uint32_t part;  // index into part_nodes
    TopoDS_Shape solid;
  };
  struct Found {
    uint32_t a, b;  // part indices, a < b
    bool collision;
    double volume;
    std::vector<TopoDS_Shape> commons;
  };
  std::vector<uint32_t> part_nodes;  // leaf node ids of the checked parts
  std::vector<Item> items;           // one per solid
  std::vector<std::pair<int, int>> pairs;
  uint64_t part_pairs = 0;
  std::vector<Found> found;          // insertion ordered
  std::map<std::pair<uint32_t, uint32_t>, size_t> index;
  uint64_t collisions = 0;
};

