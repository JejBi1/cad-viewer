/// Where the font file of an embedded font is.
pub enum FontFile {
    /// Relative to `rust/`.
    Repo(&'static str),
    /// Relative to the folder of a package of the build (found by `cargo metadata`).
    Crate { package: &'static str, path: &'static str },
}

/// A licence text that comes with an embedded font: `installer/font-licences/<local>`, and when the crate that ships the
/// font ships the same text, its path in that crate (`from_crate`, relative to the crate; both must be byte-identical).
pub struct FontNotice {
    pub local: &'static str,
    pub from_crate: Option<&'static str>,
}

/// A font file compiled into the program (`include_bytes!`), with the notices that must come with it.
pub struct EmbeddedFont {
    pub name: &'static str,
    pub file: FontFile,
    /// Copyright lines as the font file states them (name table, ID 0).
    pub copyright: &'static str,
    pub notices: &'static [FontNotice],
    /// Words the notices of this font must contain (so a notice of another font does not count).
    pub must_contain: &'static [&'static str],
}

