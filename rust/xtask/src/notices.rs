//! `cargo xtask notices`: the third-party notices text (`installer/THIRD_PARTY_NOTICES.txt`) generated from
//! `cargo metadata`: every crate that ends up in the program (normal dependencies of `cad-app` for the platform, no
//! build or dev dependencies), its licence and the licence / notice files shipped in the crate, the fonts compiled into
//! the program with their complete notices, and the parts that are not Rust crates (OCCT, LibreDWG, libiconv).
//!
//! Generation fails when an embedded font has no complete notice (so `--check` fails too). `dist` also checks that
//! every font of [`EMBEDDED_FONTS`] is really inside the executable ([`verify_fonts_in_exe`]).
use crate::occt;
use crate::util::{self, Args, LINUX_TARGET, Toolchain, WINDOWS_TARGET};
use anyhow::{Context, Result, anyhow, bail};
use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fs;
use std::path::{Path, PathBuf};

/// Where the checked-in copy of the full notices lives.
pub fn checked_in_path() -> PathBuf {
    util::rust_dir().join("xtask").join("installer").join("THIRD_PARTY_NOTICES.txt")
}

/// `cargo xtask notices [--no-dwg] [--out FILE] [--check]`
pub fn command(mut args: Args) -> Result<()> {
    let with_dwg = !args.flag("--no-dwg");
    let check = args.flag("--check");
    let out = args.value("--out")?.map(PathBuf::from).unwrap_or_else(checked_in_path);
    args.finish()?;
    let tc = Toolchain::discover()?;
    let text = generate(&tc, with_dwg, Platform::Windows)?;
    if check {
        let old = fs::read_to_string(&out).unwrap_or_default();
        if old != text {
            bail!("{} is out of date: run `cargo xtask notices`", out.display());
        }
        eprintln!("{} is up to date", out.display());
        return Ok(());
    }
    util::write_file(&out, text.as_bytes())?;
    eprintln!("wrote {} ({} bytes)", out.display(), text.len());
    Ok(())
}

