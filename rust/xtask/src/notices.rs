/// A crate whose package carries no licence file (the egui family publishes only the SPDX field): the standard text
/// of its licence with the authors from the package metadata as copyright holders. The Apache-2.0 text is taken from
/// another crate that ships it in full (see `generate`).
fn synthesize(k: &Krate, apache: Option<&str>) -> Vec<(String, String)> {
    let l = k.license.to_ascii_lowercase();
    let holders = if k.authors.is_empty() { format!("the authors of {}", k.name) } else { k.authors.join(", ") };
    let mut v = Vec::new();
    if l.contains("mit") {
        v.push(("(MIT, standardní text)".to_string(), MIT_TEXT.replace("{HOLDERS}", &holders)));
    }
    if l.contains("bsl-1.0") {
        v.push(("(BSL-1.0, standardní text)".to_string(), format!("Copyright {holders}\n\n{BSL_TEXT}")));
    }
    if l.contains("apache")
        && let Some(a) = apache
    {
        v.push(("(Apache-2.0, standardní text)".to_string(), a.to_string()));
    }
    v
}

/// The platform the notices describe: the crates of its target and the name of its program file.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Platform {
    Windows,
    Linux,
}

impl Platform {
    pub fn target(self) -> &'static str {
        match self {
            Platform::Windows => WINDOWS_TARGET,
            Platform::Linux => LINUX_TARGET,
        }
    }

    /// The program file, as the notices name it.
    pub fn exe_name(self) -> &'static str {
        match self {
            Platform::Windows => "StepViewer.exe",
            Platform::Linux => "cad-viewer",
        }
    }
}

fn cargo_metadata(tc: &Toolchain, target: &str) -> Result<Value> {
    let cargo = std::env::var_os("CARGO").map(PathBuf::from).unwrap_or_else(|| PathBuf::from("cargo"));
    let mut c = std::process::Command::new(cargo);
    tc.apply(&mut c);
    c.current_dir(util::rust_dir())
        .args(["metadata", "--format-version", "1", "--manifest-path"])
        .arg(util::rust_dir().join("Cargo.toml"))
        .args(["--filter-platform", target]);
    let out = c.output().context("starting cargo metadata")?;
    if !out.status.success() {
        bail!("cargo metadata failed:\n{}", String::from_utf8_lossy(&out.stderr));
    }
    serde_json::from_slice(&out.stdout).context("parsing cargo metadata")
}

/// Crates reachable from `cad-app` through normal dependencies, third-party ones only (workspace members have no source).
fn shipped_crates(meta: &Value) -> Result<Vec<Krate>> {
    let packages = meta["packages"].as_array().ok_or_else(|| anyhow!("no packages in metadata"))?;
    let by_id: HashMap<&str, &Value> = packages.iter().filter_map(|p| Some((p["id"].as_str()?, p))).collect();
    let nodes = meta["resolve"]["nodes"].as_array().ok_or_else(|| anyhow!("no resolve graph in metadata"))?;
    let node_of: HashMap<&str, &Value> = nodes.iter().filter_map(|n| Some((n["id"].as_str()?, n))).collect();
    let root = packages
        .iter()
        .find(|p| p["name"] == "cad-app" && p["source"].is_null())
        .and_then(|p| p["id"].as_str())
        .ok_or_else(|| anyhow!("package cad-app not found"))?;

    let mut seen: BTreeSet<&str> = BTreeSet::new();
    let mut stack = vec![root];
    while let Some(id) = stack.pop() {
        if !seen.insert(id) {
            continue;
        }
        let Some(node) = node_of.get(id) else { continue };
        for d in node["deps"].as_array().into_iter().flatten() {
            let normal = d["dep_kinds"].as_array().is_some_and(|ks| ks.iter().any(|k| k["kind"].is_null()));
            if normal && let Some(pkg) = d["pkg"].as_str() {
                stack.push(pkg);
            }
        }
    }

    let mut out = Vec::new();
    for id in seen {
        let Some(p) = by_id.get(id) else { continue };
        if p["source"].is_null() {
            continue; // workspace member: the program itself
        }
        let dir = Path::new(p["manifest_path"].as_str().unwrap_or("")).parent().map(Path::to_path_buf).unwrap_or_default();
        let mut files = find_license_files(&dir);
        if let Some(lf) = p["license_file"].as_str() {
            let path = dir.join(lf);
            if let Ok(t) = fs::read_to_string(&path) {
                let rel = lf.replace('\\', "/");
                if !files.iter().any(|(r, _)| *r == rel) {
                    files.push((rel, t));
                }
            }
        }
        out.push(Krate {
            name: p["name"].as_str().unwrap_or("?").to_string(),
            version: p["version"].as_str().unwrap_or("?").to_string(),
            license: p["license"].as_str().unwrap_or("").to_string(),
            repository: p["repository"].as_str().unwrap_or("").to_string(),
            authors: p["authors"]
                .as_array()
                .into_iter()
                .flatten()
                .filter_map(|a| a.as_str())
                .map(|a| a.split('<').next().unwrap_or(a).trim().to_string()) // names only, no e-mail addresses
                .filter(|a| !a.is_empty())
                .collect(),
            files,
        });
    }
    out.sort_by(|a, b| (a.name.as_str(), a.version.as_str()).cmp(&(b.name.as_str(), b.version.as_str())));
    Ok(out)
}

fn is_license_name(name: &str) -> bool {
    let n = name.to_lowercase();
    let stem = n.split('.').next().unwrap_or("");
    // texts only: no sources, data or images that happen to start with "license"
    let ext_ok = match n.rsplit_once('.') {
        None => true,
        Some((_, e)) => !matches!(
            e,
            "rs" | "toml" | "json" | "html" | "htm" | "png" | "svg" | "c" | "h" | "cpp" | "hpp" | "py" | "js" | "yml" | "yaml"
                | "lock" | "xml" | "sh" | "in" | "pdf" | "jpg" | "ico"
        ),
    };
    let name_ok = ["license", "licence", "copying", "copyright", "notice", "unlicense", "patents"].iter().any(|p| stem.starts_with(p))
        || stem == "ofl"
        || stem == "ufl"
        || stem.starts_with("ofl-")
        || stem.starts_with("ufl-");
    ext_ok && name_ok
}

/// Licence, copying and notice files of a crate (depth <= 3, vendored third-party folders included; sources, tests
/// and examples are skipped).
fn find_license_files(dir: &Path) -> Vec<(String, String)> {
    fn walk(base: &Path, dir: &Path, depth: usize, out: &mut Vec<(String, String)>) {
        let Ok(rd) = fs::read_dir(dir) else { return };
        let mut entries: Vec<_> = rd.flatten().collect();
        entries.sort_by_key(|e| e.file_name());
        for e in entries {
            let p = e.path();
            let name = e.file_name().to_string_lossy().into_owned();
            let Ok(ty) = e.file_type() else { continue };
            if ty.is_dir() {
                let l = name.to_lowercase();
                if depth < 3 && !matches!(l.as_str(), "tests" | "test" | "benches" | "examples" | "docs" | "doc" | "target" | "fuzz" | "ci" | "node_modules")
                    && !l.starts_with('.')
                {
                    walk(base, &p, depth + 1, out);
                }
            } else if ty.is_file() && is_license_name(&name) {
                if e.metadata().map(|m| m.len()).unwrap_or(0) > 300_000 {
                    continue;
                }
                if let Ok(bytes) = fs::read(&p) {
                    let text = String::from_utf8_lossy(&bytes).into_owned();
                    let rel = p.strip_prefix(base).unwrap_or(&p).to_string_lossy().replace('\\', "/");
                    out.push((rel, text));
                }
            }
        }
    }
    let mut out = Vec::new();
    walk(dir, dir, 0, &mut out);
    out
}

fn normalize(text: &str) -> String {
    let t = text.trim_start_matches('\u{feff}').replace("\r\n", "\n").replace('\r', "\n");
    let lines: Vec<&str> = t.lines().map(str::trim_end).collect();
    lines.join("\n").trim().to_string()
}

/// The notices text. `with_dwg` adds the LibreDWG section (the converter is part of the package).
pub fn generate(tc: &Toolchain, with_dwg: bool, platform: Platform) -> Result<String> {
    let meta = cargo_metadata(tc, platform.target())?;
    let mut crates = shipped_crates(&meta)?;
    // the full Apache-2.0 text, from any crate that ships it
    let apache: Option<String> = crates
        .iter()
        .flat_map(|k| k.files.iter())
        .map(|(_, t)| normalize(t))
        .find(|t| t.contains("Apache License") && t.contains("Version 2.0, January 2004") && t.contains("END OF TERMS AND CONDITIONS"));
    let mut synthesized: Vec<String> = Vec::new();
    for k in crates.iter_mut().filter(|k| k.files.is_empty()) {
        let files = synthesize(k, apache.as_deref());
        if !files.is_empty() {
            synthesized.push(format!("{} {} ({})", k.name, k.version, k.license));
            k.files = files;
        }
    }
    let source_url = source_repository();
    let mut s = String::new();
    let line = "=".repeat(78);

    s.push_str(&format!("CAD prohlížeč {} – licence a oznámení třetích stran\n{line}\n\n", util::VERSION));
    s.push_str(
        "Tento soubor vzniká příkazem `cargo xtask notices` z metadat Cargo (cargo metadata) a z podkladů v repozitáři.\n\
         Obsahuje všechny součásti, které jsou ve spustitelném souboru nebo vedle něj.\n\n",
    );

    s.push_str("1. Program\n----------\n");
    s.push_str(&format!(
        "CAD prohlížeč {} je svobodný software šířený podle licence GNU General Public License verze 3 (GPL-3.0-only.txt).\n\
         Úplný zdrojový kód této verze včetně skriptů pro sestavení (rust/xtask) je zde:\n  {}\n\n",
        util::VERSION,
        if source_url.is_empty() { "u vydavatele programu".to_string() } else { source_url.clone() }
    ));

    s.push_str("2. Open CASCADE Technology 8.0.1 (3D jádro)\n--------------------------------------------\n");
    s.push_str(&format!(
        "Tento program používá a je založen na technologii Open CASCADE Technology (OCCT).\n\
         Licence: GNU LGPL 2.1 s výjimkou Open CASCADE verze 1.0 (LGPL-2.1-only.txt, OCCT_LGPL_EXCEPTION.txt).\n\
         Zdrojový kód: https://github.com/Open-Cascade-SAS/OCCT, vydání V8_0_1 (commit {}).\n\
         Archiv se zdrojovým kódem: {}\n  SHA-256 {}\n\
         Od verze 2.0 je OCCT přilinkováno staticky do {exe} (verze 1.9 ho měla jako samostatnou {v19}). Knihovny jsou\n\
         sestavené z nezměněného zdrojového kódu příkazem `cargo xtask occt-static` (rust/xtask/src/occt.rs; volby CMake\n\
         jsou v repozitáři) a obsahují jen tyto celky: {}.\n\
         Žádná volitelná knihovna třetích stran (FreeType, FreeImage, VTK, TBB, RapidJSON, Draco, Tcl/Tk, OpenGL) se nepoužívá.\n\
         Program je šířen s úplným zdrojovým kódem pod licencí GPL-3.0, takže ho lze s upravenou verzí OCCT znovu sestavit\n\
         (`cargo xtask occt-static`, potom `cargo xtask dist`).\n\n",
        occt::SOURCE_COMMIT,
        occt::ARCHIVE_URL,
        occt::ARCHIVE_SHA256,
        installed_toolkits(),
        exe = platform.exe_name(),
        v19 = if platform == Platform::Windows { "DLL" } else { "sdílenou knihovnu" },
    ));

    s.push_str(&font_section(&meta)?);

    if with_dwg {
        s.push_str(&dwg_section(platform));
    } else if platform == Platform::Windows {
        s.push_str(
            "4. Převodník DWG (LibreDWG)\n---------------------------\n\
             Tato sestava neobsahuje převodník DWG -> DXF. Je ve zvláštním balíčku (StepViewer-dwg-addon), který má vlastní\n\
             oznámení o licencích (licenses/THIRD_PARTY_NOTICES_DWG.txt).\n\n",
        );
    } else {
        s.push_str(
            "4. Převodník DWG\n----------------\n\
             Tato sestava (bez DWG) neobsahuje převodník DWG -> DXF; výkresy DWG se v ní neotevřou.\n\n",
        );
    }

    s.push_str(&format!("5. Knihovny Rust ({} balíčků ve spustitelném souboru)\n{}\n", crates.len(), "-".repeat(60)));
    for k in &crates {
        s.push_str(&format!(
            "  {} {} – {}{}\n",
            k.name,
            k.version,
            if k.license.is_empty() { "(licence viz text)" } else { &k.license },
            if k.repository.is_empty() { String::new() } else { format!(" – {}", k.repository) }
        ));
    }
    s.push('\n');

    // 5. all distinct licence / notice texts, each with the crates it belongs to
    let mut texts: BTreeMap<String, (String, BTreeSet<String>)> = BTreeMap::new();
    let mut without: Vec<String> = Vec::new();
    for k in &crates {
        if k.files.is_empty() {
            without.push(format!("{} {} ({})", k.name, k.version, k.license));
        }
        for (_, t) in &k.files {
            let norm = normalize(t);
            if norm.is_empty() {
                continue;
            }
            let key = util::sha256_bytes(norm.as_bytes());
            texts.entry(key).or_insert_with(|| (norm, BTreeSet::new())).1.insert(format!("{} {}", k.name, k.version));
        }
    }
    s.push_str(&format!("6. Texty licencí a oznámení autorů ({} různých textů)\n{}\n\n", texts.len(), "-".repeat(60)));
    if !synthesized.is_empty() {
        s.push_str("Balíčky bez vlastního souboru s licencí (licence podle metadat balíčku; níže je standardní text licence se jmény autorů z metadat):\n");
        for w in &synthesized {
            s.push_str(&format!("  {w}\n"));
        }
        s.push('\n');
    }
    if !without.is_empty() {
        eprintln!("notices: WARNING {} crates have no licence text at all: {}", without.len(), without.join(", "));
        s.push_str("Balíčky, pro které se text licence nepodařilo doplnit (licence podle metadat balíčku):\n");
        for w in &without {
            s.push_str(&format!("  {w}\n"));
        }
        s.push('\n');
    }
    let mut ordered: Vec<_> = texts.into_values().collect();
    ordered.sort_by(|a, b| a.1.iter().next().cmp(&b.1.iter().next()));
    for (i, (text, owners)) in ordered.iter().enumerate() {
        s.push_str(&format!("{line}\nText {} – platí pro: {}\n{line}\n{text}\n\n", i + 1, owners.iter().cloned().collect::<Vec<_>>().join(", ")));
    }
    Ok(s)
}

/// Toolkits of the installed static OCCT (the closure CMake built), else the ones the bridge asks for.
fn installed_toolkits() -> String {
    occt::read_manifest(&occt::default_prefix(occt::Crt::Static))
        .map(|m| m.toolkits)
        .ok()
        .filter(|t| !t.is_empty())
        .map(|t| t.join(", "))
        .unwrap_or_else(|| occt::ROOT_TOOLKITS.join(", "))
}

fn source_repository() -> String {
    std::process::Command::new("git")
        .args(["-C"])
        .arg(util::repo_root())
        .args(["config", "--get", "remote.origin.url"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().trim_end_matches(".git").to_string())
        .filter(|u| u.starts_with("https://"))
        .unwrap_or_default()
}

