fn font_licence_dir() -> PathBuf {
    util::rust_dir().join("xtask").join("installer").join("font-licences")
}

/// The folder of the package `name` in the build (where its manifest is).
fn package_dir(meta: &Value, name: &str) -> Result<PathBuf> {
    let p = meta["packages"]
        .as_array()
        .into_iter()
        .flatten()
        .find(|p| p["name"] == name && p["source"].is_string())
        .ok_or_else(|| anyhow!("package {name} is not part of the build, so its embedded fonts cannot be checked"))?;
    Path::new(p["manifest_path"].as_str().unwrap_or(""))
        .parent()
        .map(Path::to_path_buf)
        .ok_or_else(|| anyhow!("package {name}: no folder for its manifest"))
}

fn font_path(meta: &Value, f: &EmbeddedFont) -> Result<PathBuf> {
    match &f.file {
        FontFile::Repo(p) => Ok(util::rust_dir().join(p)),
        FontFile::Crate { package, path } => Ok(package_dir(meta, package)?.join(path)),
    }
}

/// Section 3 of the notices: every embedded font with its copyright lines and its complete licence text. Fails when a
/// font file, a notice, or the copy of a crate's notice is missing or differs, or when a notice does not name the
/// licence of its font.
fn font_section(meta: &Value) -> Result<String> {
    let line = "-".repeat(60);
    let mut s = String::from("3. Písma vložená do programu\n----------------------------\n");
    s.push_str("Program obsahuje tato písma (include_bytes!); `cargo xtask dist` ověří, že jsou v souboru programu.\n\n");
    for f in EMBEDDED_FONTS {
        let file = font_path(meta, f)?;
        if !file.is_file() {
            bail!("embedded font {}: the font file {} is missing", f.name, file.display());
        }
        let mut licence = String::new();
        let mut names: Vec<&str> = Vec::new();
        for n in f.notices {
            let local = font_licence_dir().join(n.local);
            let bytes = fs::read(&local).map_err(|_| {
                anyhow!("embedded font {}: its notice {} is missing (expected {})", f.name, n.local, local.display())
            })?;
            if let Some(rel) = n.from_crate {
                let FontFile::Crate { package, .. } = &f.file else {
                    bail!("embedded font {}: its notice is copied from a crate, but the font is not from one", f.name);
                };
                let shipped = package_dir(meta, package)?.join(rel);
                let same = fs::read(&shipped).map(|b| b == bytes).unwrap_or(false);
                if !same {
                    bail!(
                        "embedded font {}: {} differs from {} (copy the notice from the crate again)",
                        f.name,
                        local.display(),
                        shipped.display()
                    );
                }
            }
            licence.push_str(&normalize(&String::from_utf8_lossy(&bytes)));
            licence.push_str("\n\n");
            names.push(n.local);
        }
        for m in f.must_contain {
            if !licence.contains(m) {
                bail!("embedded font {}: its notice does not contain \"{m}\"", f.name);
            }
        }
        s.push_str(&format!("{}\n", f.name));
        s.push_str(&format!("  autorská práva: {}\n", f.copyright.split_whitespace().collect::<Vec<_>>().join(" ")));
        s.push_str(&format!("  licence: {}\n\n", names.join(", ")));
        s.push_str(&licence);
        s.push_str(&format!("{line}\n\n"));
    }
    Ok(s)
}

/// 256 bytes from the middle of a font file: enough to find the font in the executable.
fn font_sample(bytes: &[u8]) -> &[u8] {
    let mid = bytes.len() / 2;
    &bytes[mid..mid + 256]
}

/// `cargo xtask dist`: every font of [`EMBEDDED_FONTS`] is in the executable (a 256-byte sample from the middle of each
/// font file is searched in the executable), so the notices describe what really ships. Returns the font names.
pub fn verify_fonts_in_exe(tc: &Toolchain, exe: &Path, platform: Platform) -> Result<Vec<&'static str>> {
    let meta = cargo_metadata(tc, platform.target())?;
    let image = fs::read(exe).with_context(|| exe.display().to_string())?;
    let contains = |sample: &[u8]| image.windows(sample.len()).any(|w| w == sample);
    let mut found = Vec::new();
    let mut listed: Vec<PathBuf> = Vec::new();
    for f in EMBEDDED_FONTS {
        let file = font_path(&meta, f)?;
        let bytes = fs::read(&file).with_context(|| file.display().to_string())?;
        if bytes.len() < 1024 {
            bail!("font file {} is too small to check", file.display());
        }
        if !contains(font_sample(&bytes)) {
            bail!(
                "embedded font {} is not in {}: the font list in rust/xtask/src/notices.rs is out of date",
                f.name,
                exe.display()
            );
        }
        found.push(f.name);
        listed.push(file);
    }
    // the other way round: a font file of the font folders that the program contains but the list does not name
    let folders = [
        package_dir(&meta, "epaint_default_fonts")?.join("fonts"),
        util::rust_dir().join("crates").join("cad-2d").join("assets"),
    ];
    for dir in folders {
        for entry in fs::read_dir(&dir).with_context(|| dir.display().to_string())? {
            let p = entry?.path();
            let is_font = p.extension().is_some_and(|e| e.eq_ignore_ascii_case("ttf") || e.eq_ignore_ascii_case("otf"));
            if !is_font || listed.contains(&p) {
                continue;
            }
            let bytes = fs::read(&p).with_context(|| p.display().to_string())?;
            if bytes.len() >= 1024 && contains(font_sample(&bytes)) {
                bail!(
                    "font {} is in {} but not in the list of embedded fonts (rust/xtask/src/notices.rs): its notice is missing",
                    p.display(),
                    exe.display()
                );
            }
        }
    }
    Ok(found)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn licence_file_names() {
        for yes in ["LICENSE", "LICENSE-MIT", "license-apache-2.0", "COPYING", "COPYING.LESSER", "NOTICE", "UNLICENSE", "OFL.txt", "UFL.txt", "LICENSE.md"] {
            assert!(is_license_name(yes), "{yes}");
        }
        for no in ["lib.rs", "Cargo.toml", "license.rs", "README.md", "licensing.html", "build.rs"] {
            assert!(!is_license_name(no), "{no}");
        }
    }

    #[test]
    fn normalisation_makes_equal_texts_equal() {
        assert_eq!(normalize("\u{feff}MIT  \r\nText\r\n\r\n"), normalize("MIT\nText"));
    }

    #[test]
    fn mit_text_gets_holders() {
        let k = Krate { name: "x".into(), version: "1".into(), license: "MIT OR Apache-2.0".into(), repository: String::new(), authors: vec!["A B".into(), "C D".into()], files: vec![] };
        let v = synthesize(&k, Some("APACHE"));
        assert_eq!(v.len(), 2);
        assert!(v[0].1.contains("Copyright (c) A B, C D"));
        assert_eq!(v[1].1, "APACHE");
    }

    #[test]
    fn every_embedded_font_has_its_complete_notice() {
        assert!(!EMBEDDED_FONTS.is_empty());
        for f in EMBEDDED_FONTS {
            let mut all = String::new();
            for n in f.notices {
                let p = font_licence_dir().join(n.local);
                let bytes = fs::read(&p).unwrap_or_else(|_| panic!("notice of {} missing: {}", f.name, p.display()));
                all.push_str(&normalize(&String::from_utf8_lossy(&bytes)));
            }
            for m in f.must_contain {
                assert!(all.contains(m), "{}: notice does not contain {m}", f.name);
            }
        }
    }

    #[test]
    fn dejavu_notice_is_the_bitstream_vera_licence() {
        let t = fs::read_to_string(font_licence_dir().join("DejaVuSans-LICENSE.txt")).unwrap();
        assert!(t.contains("Bitstream Vera Fonts Copyright"));
        assert!(t.contains("THE FONT SOFTWARE IS PROVIDED"));
    }

    #[test]
    fn dwg_section_names_the_platform_files() {
        assert!(dwg_section(Platform::Windows).contains("dwg2dxf.exe"));
        assert!(dwg_section(Platform::Linux).contains("third_party/libredwg-linux"));
        assert!(!dwg_section(Platform::Linux).contains(".dll"));
    }
}
